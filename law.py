# ── 类型路由(缺省规则; 名单显式给 type 时优先) ─────────────────────────
def route_type(title: str) -> str:
    t = title.replace(" ", "")
    if re.search(r"以.{2,20}(案|号|为例)|——?[（(]?\d{4}[）)]?", t):
        return "T1"
    if re.search(r"问题|对策|完善|研究|思考|探析|浅析|制度", t) and not re.search(r"为例", t):
        return "T2"
    return "T2"   # 无单案指涉默认类型二(案例群更易凑)

# ── 选题: 案例→题目(规则版; 生产环境可换LLM扩展同签名) ────────────────
def derive_title_t1(case: dict) -> str:
    """单案例 → 类型一题目: 《XX纠纷的司法认定——以某某案为例》"""
    return f"{case.get('案由', '民事纠纷')}中{case.get('核心争点短语', '法律问题')}的司法认定——以{case.get('名称', '某案')}为例"

def derive_title_t2(cluster: list, domain: str) -> str:
    """案例群 → 类型二题目: 《XX领域XX问题研究——基于N起典型案例的分析》"""
    return f"{domain}司法实践中的{cluster[0].get('共性问题短语', '突出问题')}研究——基于{len(cluster)}起典型案例的分析"

# ── 分章prompt(素材注入 + 禁编令) ────────────────────────────────────
CASE_MATERIAL_BLOCK = """【案例素材·唯一事实来源(禁止虚构任何案情细节)】
名称: {名称}
案号: {案号}
当事人: {当事人}
案由: {案由}
基本事实: {基本事实}
诉讼请求: {诉讼请求}
裁判结果: {裁判结果}
争议焦点: {争议焦点}
来源: {来源} {来源链接}
写作铁律:
1. 凡涉及本案的当事人姓名、案号、事实经过、诉请、裁判结果, 只能使用上述素材原文, 一字不得虚构;
2. 引用素材未提及的案情细节属于违规;
3. 提及案例时必须标注来源({来源});
4. 法条引用须为现行有效条文, 写明"《XX法》第X条";
5. 法学书面语, 三段论/要件式论证, 禁口语化表达。"""

def build_case_block(case: dict) -> str:
    return CASE_MATERIAL_BLOCK.format(**{**{
        "名称": "", "案号": "", "当事人": "", "案由": "", "基本事实": "", "诉讼请求": "",
        "裁判结果": "", "争议焦点": "", "来源": "", "来源链接": ""}, **case})

def build_chapter_prompt(paper_type: str, chapter: str, seq: int, word_limit: int,
                         title: str, case_blocks: list, prev_summary: str = "") -> str:
    """组装单章生成prompt。case_blocks: [build_case_block(c) for c in cases]"""
    blocks = "\n\n".join(case_blocks)
    ctx = f"\n【前文摘要(保持衔接, 勿重复)】\n{prev_summary[:1200]}\n" if prev_summary else ""
    return f"""你是法学本科毕业论文写作者。论文题目: 《{title}》({paper_type}型)。
本篇论文的案例素材如下(全部真实, 引用时标注来源):
{blocks}
{ctx}
现在撰写第{seq}章「{chapter}」, 要求:
- 字数{word_limit}字左右(不超过{int(word_limit*LAW_SOFT_MAX_RATIO)}字);
- 按本章功能组织(若为案件章: 事实/诉请/裁判; 若为分析章: 事实依据→法律依据→学理观点(至少两种)→本文见解);
- 案号/当事人/裁判结果只准引用素材; 学理观点可引通说与有力学说;
- 输出纯正文文本(不要章标题行, 不要markdown)。"""

