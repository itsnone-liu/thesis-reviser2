"""
经管类论文提示词模板
按章节分类，重点解决：
1. 前几章markdown残留（表格/粗体/标题符号）
2. 图表标签规范输出
3. 按实际需要输出，不设硬性下限
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))
from core import MG_WORD_LIMITS, MG_SOFT_MAX

FMT_RULE = """
【格式铁律 - 必须严格遵守】
1. 严禁使用任何markdown符号：# ** * ` 
2. 严禁在正文中使用markdown表格、引用或分隔线；但 <chart/> 与 <table/> 标签内部允许使用必要的属性符号
3. 严禁使用加粗标记，所有文字统一纯文本
4. 段落之间用换行分隔，不要用空行
5. 所有结构化标签必须原样保留为 <chart .../>、<table .../>，不要把 `/>` 改写成 `/`、`/>/` 或漏掉 `>`
6. 【表格硬约束】如果使用 <table/>，rows 里只能放“行名/维度名”，每个名称只出现一次；年份、分值、百分比、结论、趋势说明一律放到 data 里
"""

OUTPUT_CHECKLIST = """
【输出前自检 - 逐项核对】
1. 文中是否还有markdown表格符号（| --- |）？→ 有则删除
2. 文中是否还有**加粗**或#标题？→ 有则删除
3. <chart/>标签的y属性是否只包含数字（如 y="32.5,35.7"），没有文字？→ 否则修改
4. <table/>标签的rows是否只放行名（如 rows="收入,成本"），没放数据？→ 否则修改
5. 所有<chart/> <table/>标签是否都已正确闭合（/>）？→ 否则补全
6. 如果这一章没有需要展示的数据，是否需要<chart/>或<table/>标签？→ 不需要就不输出
7. 【维度完整性】正文中提到的每个维度/系列是否都有<chart/>或<table/>覆盖？不允许遗漏任何一个 → 缺则补全
8. 【系列数一致】多系列<chart/>的legend系列名称数量是否等于y中用分号分隔的段数？→ 否则修正
9. 【年份完整性】正文提到的每个年份/分类是否都在x属性中出现？缺失年份不能删系列 → 必须按正文语义补齐
10. 【表格维度】表格rows是否覆盖了正文中出现的所有维度？data是否保留了所有行和列？→ 缺则补全
11. 【表格结构】rows 中绝不能出现数字、百分比、年份、趋势词、结论词；一旦出现，说明 rows 已经污染，必须重写成纯行名列表
12. 【表格模板】任何四列及以上的对比表，优先把“对比项”放在 rows，其他字段全部放在 data，不要把整行复制进 rows
"""

CHART_RULE = """
【图表输出规范 - 必须遵守】
- 文中涉及数据对比、趋势分析、统计结果、结构拆分的地方，必须使用<chart/>或<table/>标签
- 严禁用文字罗列数据（如"2020年100万，2021年150万"）
- 图表里的数据必须完整覆盖正文提到的维度/系列，不能为了简化而删维度、删线、删列
- 正文如果写到了多个指标/多个系列/多个年份，图表中必须全部出现
- 缺失年份或缺失值不能靠删系列解决，必须按正文语义补齐为可绘图数据
- 不得输出null、空位、省略号来逃避补齐；如果确实无法补齐，则重写该图或改成表格
- 必须使用指定标签格式，不要用markdown
- 【表格强制约束】章节"现状分析"、"问题与原因分析"、"解决方案"每章必须包含至少1个<table/>标签，结构化数据（指标对比/评分体系/方案比较/风险矩阵等）优先用表格
- 【table数据格式】data中分号;分隔行，竖线|分隔列。rows的行名数×data的;段数必须一致。严禁在rows属性中放多列数据
- 【表格优先原则】如果某段内容已经出现年份、指标、对比项或比例数据，优先输出<table/>，不要只输出文字概述
- 【表格保底要求】每个含数据分析的小节，至少要给出1个结构化表格或图表；若图表已出现，仍建议补1个表格做数据明细

<chart>格式模板（严格按此格式，逐项填写）：

【单系列格式（一条线/一组柱）】
<chart id="1" title="图表标题" type="bar" x="2020年,2021年,2022年" y="100,150,200" unit="万元" data_source="来源"/>

【多系列格式（多条线/多组柱/堆叠/对比）】
<chart id="2" title="图表标题" type="line" x="2020年,2021年,2022年" y="68.5,71.2,74.2;45.6,48.2,52.0" legend="资产负债率,流动负债占比" unit="%" data_source="来源"/>
说明：y中用分号;分隔多个系列的数据，legend中用逗号分隔系列名称。系列数量、每个系列的数据点数、x轴分类数必须一致。

【图类型约束 - type可选值】
- bar: 柱状图（单组对比）
- line: 折线图（单条或多条趋势线）
- stacked: 堆叠柱状图/堆叠面积图（构成比）
- pie: 饼图/环形图（占比分布）
- comparison: 对比图（多组横向对比）
- trend: 趋势图（时间序列趋势，等价于line）
- structure: 结构图（层级/构成关系，如组织架构）
- gantt: 甘特图（进度计划）
- table_format: 表格形式（结构化数据）
如不在此列则用最接近的类型。

【维度完整性铁律 - 最高优先级】
- 正文提到了N个维度/系列（例如"营收、成本、利润"三个系列），<chart/>必须同时展示全部N个
- 禁止：正文讨论"资产负债率、流动负债占比"两个系列，但只输出一个系列的数据
- 正确做法：输出一个多系列<chart/>（y中包含两组数据，用分号分隔），或分别输出多个单系列<chart/>
- 无论单系列还是多系列，正文中出现的每个维度必须有对应的数据在<chart/>中呈现
- 图例名称（legend中的值）必须与正文中的维度名称一致

【数据补齐规则 - 缺失年份/缺失数据如何处理】
- 如果正文提到了某个年份或分类，但该系列在该年份缺少数据：不可删除该年份x坐标，更不可删除整个系列
- 缺失的数据保留空位（例如 y="100,150,,200" 表示第三年数据缺失），或用0填充并在正文中说明
- 例如：讨论2020-2024五年趋势，某系列只有2020-2023年数据 → x仍保留"2020年,2021年,2022年,2023年,2024年"，y中2024年位置留空或填估算值
- 不得因为某系列数据点不完整就从图表中删除该系列

【致命错误1 - y属性写了文字不是数字】
   错误：y="单位直接材料成本(元),单位直接人工成本(元),单位制造费用(元)"
   正确：y="32.5,35.7,38.7"
   原因：y属性只能填数字，不能填文字标签。

【致命错误2 - 系列数据长度不匹配】
   错误：y="68.5,71.2,74.2;45.6,48.2"（第二个系列数据点比第一个少）
   正确：y="68.5,71.2,74.2;45.6,48.2,52.0"
   原因：多系列时每个系列的y值数量必须相等，且等于x中的分类数。

【致命错误3 - 维度/系列遗漏】
   错误：正文讨论了"营收、成本、利润"三个维度，但图表只输出 y="100,200,300"（仅营收一个系列）
   正确：y="100,200,300;60,80,120;30,40,50" legend="营收,成本,利润"
   原因：正文中出现的每个维度都必须出现在图表中，不能简化成单系列。

【标签自检规则】
- id属性：用纯数字编号（1,2,3...），不要用"3-2"这种格式。chart/table的id必须在整篇论文中全局唯一，不能按章节重置（例如第3章用了id="1"，第4章就不能再用id="1"）
- y属性：只能含数字、小数点、逗号和分号。含中文字符，必错！
- x属性：分类标签，可以用文字如"2020年,2021年,2022年"
- legend属性：多系列时必填，系列名称数量必须等于y中分号段数
- unit属性：y值的单位文字
- 标签末尾必须有/>，不能只有>

【表格格式模板（严格按此格式）】
<table id="1" title="表格标题" header="指标,2020年,2021年,2022年" rows="收入,成本,利润" data="100|200|300;50|80|120;30|40|50" data_source="来源"/>
说明：rows="行名1,行名2,行名3" 对应 data="行1列1|行1列2|行1列3;行2列1|行2列2|行2列3"
每行数据用分号;分隔，每列数据用竖线|分隔。rows数量必须等于data的分号段数。
- 【强制】data属性必须使用竖线|分隔列，使用分号;分隔行。禁止使用逗号作为列分隔符。
- 【禁止】rows 里不要出现“行名,数值,数值,数值”这种整行展开写法；如果每个 rows 项后面还有数字或结论，说明表格格式错误，必须改成标准矩阵

【5列4行参数对比表示例】
<table id="2" title="供应商评价指标体系" header="一级指标,二级指标,权重,评分标准,得分" rows="质量,合格率,0.25,≥98%得满分,92;成本,价格水平,0.20,低于行业均值5%得满分,88;交付,准时率,0.30,≥95%得满分,95;服务,响应速度,0.25,24h内响应得满分,85" data_source="来源"/>

【表格维度完整性规则】
- rows中的行名数量必须等于data中用;分隔的段数
- 每个段内用|分隔的列数必须等于header中的列数减1
- 严禁将多列数据合并写入一行或rows中

【表格维度完整性规则】
- rows中的行名必须覆盖正文中提到的所有维度/系列，不得遗漏
- 例如正文讨论了"收入、成本、利润、税金"四个维度 → rows="收入,成本,利润"错误，缺少"税金"
- data的行数必须等于rows中的行数，列数必须等于header中的列数减1
- 缺失数据不能删行删列，必须按正文语义补齐为可展示的数据

【表格自检规则】
- rows属性：只放行名称！每行一个名称，用逗号分隔。格式：rows="行1,行2,行3"
- data属性：同行数据用|分隔，不同行用;分隔。格式：data="行1列1|行1列2;行2列1|行2列2"
- 行名数量 == data用;分隔的行数
- 每行数据列数 == header的列数
- 如果本章出现了图表分析内容但还没有表格，请优先补一个与图表同源的数据表

【核心原则】
标签是"数据容器"，不要放正文内容进去。正文用段落描述分析，标签只负责结构化数据。

【土木工程特别约束】
10. 截面配筋对比、荷载对比、材料用量对比等结构化对比数据，必须使用 <table/> 标签
11. <chart/> 的 y 属性只能填纯数字（如 y="100,200,300"），禁止填文字
12. 如果某段数据既有文字列又有数字列（如"构件,截面,配筋"），必须用 <table/>
13. 严禁使用 <chart type="table"> 这种格式
【y的组织方式 - 必须用 series-major】
- y 的数据必须按系列（series）排列，不能按分类（category）排列。
- 格式：y="系列1全部值;系列2全部值;系列3全部值"（series-major）。
- 禁止：y="分类1的系列值们;分类2的系列值们"（category-major）。

【comparison / bar / line 等对比图要求】
- x = 分类轴（如年份/账龄段）
- legend = 对比组名（如"优化前,优化后"、"2023,2024"）
- y = 每个 legend 组的完整数据段，段内数据点顺序与 x 一一对应
- 例如"优化前后对比" → x="2021年,2022年,2023年" legend="优化前,优化后" y="68.5,71.2,74.2;45.6,48.2,52.0"
- 账龄结构：x="1年内,1-2年,2-3年" legend="2023年,2024年" y="60,25,15;50,30,20"
- 两个 legend 名 → y 有且仅有 2 段（用分号分隔）
- y 段数必须恒等于 legend 项数，不得多段或少段
"""


def build_chapter_prompt(chapter_name: str, chapter_num: int, profile: dict) -> str:
    """构造单章节的生成提示词"""
    title = profile.get("title", "")
    company = profile.get("company", "")
    industry = profile.get("industry", "")
    word_limit = MG_WORD_LIMITS.get(chapter_name, 1000)

    # 各章特殊要求
    special_rules = {
        "引言": """
【引言特殊要求】
- 用2-3段写背景和意义，不要任何标题编号
- 不要写"第1章"或"第一章"
- 纯叙述性文字
""",
        "国内外研究现状": f"""
【国内外研究现状特殊要求】
- 纯段落叙述，不要写标题编号
- 不要提到{company}，只讨论学术研究
- 分国外、国内两部分叙述
""",
        "现状分析": f"""
【现状分析特殊要求】
- 小标题格式：3.1、3.2、3.3
- 围绕{company}的现状展开
- 数据对比处必须使用<chart/>或<table/>标签
""",
        "问题与原因分析": """
【问题与原因分析特殊要求】
- 小标题格式：4.1、4.2、4.3
- 先列出问题，再分析原因
- 数据对比处必须使用<chart/>或<table/>标签
""",
        "解决方案": """
【解决方案特殊要求】
- 小标题格式：5.1、5.2、5.3
- 针对问题逐一提出方案
- 数据对比处必须使用<chart/>标签
""",
        "结论": """
【结论特殊要求】
- 300-500字总结
- 无标题编号，不要写"第6章"
""",
    }

    sp = special_rules.get(chapter_name, "")
    cr = CHART_RULE if chapter_name in ["现状分析", "问题与原因分析", "解决方案"] else ""

    prompt = f"""你是一名经管类学术论文写作专家。写《{title}》第{chapter_num}章 {chapter_name}。
字数要求：{word_limit}字以内。
{FMT_RULE}
{sp}
{cr}
研究对象：{company}
所属行业：{industry}

只输出正文内容，不要输出"第{chapter_num}章"字样。"""
    return prompt


def build_abstract_prompt(profile: dict) -> str:
    """生成摘要提示词"""
    return f"""写300字论文摘要。
题目：{profile.get('title', '')}
研究对象：{profile.get('company', '')}
行业：{profile.get('industry', '')}
核心问题：{profile.get('core_problems', [])}
{FMT_RULE}
只输出摘要正文，不要"摘要"二字。"""


def build_keywords_prompt(profile: dict) -> str:
    """生成关键词提示词"""
    return f"""根据以下信息生成3-5个关键词，用分号隔开。
标题：{profile.get('title', '')}
行业：{profile.get('industry', '')}
只输出关键词，如：关键词1；关键词2；关键词3"""


def build_references_prompt(profile: dict) -> str:
    """生成参考文献提示词"""
    return f"""生成12-15条规范参考文献，类型包括书籍[M]、期刊论文[J]、学位论文[D]。
主题：{profile.get('title', '')}、{profile.get('industry', '')}相关理论。
每条占一行，格式如：[1] 作者. 书名[M]. 出版社, 年份."""
