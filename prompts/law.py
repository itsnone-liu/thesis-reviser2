# 每章功能指令(评阅要求的框架语义; 编号规则统一在prompt模板中)
CH_GUIDE = {
    "引言": "三节: 选题背景(新就业形态用工的发展态势与劳动关系认定争议) / 研究意义(理论与实践两层) / 案例来源与选择理由(写明本案来源于最高人民法院发布的指导性案例, 并标注来源)。",
    "案件事实与诉讼请求": "三节: 基本事实(当事人情况、案件经过、关键事实) / 当事人诉讼请求(与答辩意见) / 裁判结果。本章开头必须写明案例来源与案号(素材中的案号和来源原文照抄)。案情只准使用素材内容, 禁止扩充细节。",
    "争议焦点归纳": "从素材的争议焦点出发, 归纳二至三个焦点; 每个焦点一节, 阐明其为何构成本案核心矛盾, 为下文分析铺垫。",
    "争议焦点分析": "对每个争议焦点依次展开四层: 事实依据分析; 法律依据分析(引用现行有效法条, 写明《法律名》第X条); 学理观点评析(至少两种学说, 概述其分歧); 本文见解(观点明确、论证充分)。每个焦点一节。",
    "结论与启示": "三节: 研究结论(逐焦点回应); 对司法实践的启示(支配性劳动管理标准的适用要点); 研究局限与展望。",
    "结语": "简短收束全文, 不引入新论点, 不分节。",
}

def build_chapter_prompt(title: str, case: dict, chapter: str, seq: int,
                         word_limit: int, prev_summary: str = "") -> str:
    guide = CH_GUIDE.get(chapter, "按本章在论文中的功能组织论证。")
    ctx = f"\n【前文摘要(保持衔接, 勿重复)】\n{prev_summary[:1000]}\n" if prev_summary else ""
    return f"""你是法学本科毕业论文写作者。论文题目: 《{title}》(案例分析型)。

{build_case_block(case)}
{ctx}
现在撰写第{seq}章「{chapter}」。本章写作要求:
{guide}
- 小节标题编号规则(严格执行): 二级标题用"{seq}.1 标题文字"、"{seq}.2 标题文字"…独占一行; 如需三级标题用"{seq}.1.1 标题文字"; 禁止使用(一)(二)(三)、一、二、三等中文编号;
- 字数{word_limit}字左右(上限{int(word_limit * LAW_SOFT_MAX_RATIO)}字);
- 法学书面语, 三段论/要件式论证, 禁止口语化;
- 输出纯正文(不要章标题行, 不要markdown符号)。"""

def build_abstract_prompt(title: str, case: dict) -> str:
    return f"""你是法学本科毕业论文写作者。论文题目: 《{title}》。

{build_case_block(case)}

请撰写论文摘要, 要求:
- 300至500字, 单段;
- 覆盖: 研究对象与案例来源(标注指导性案例来源)、争议焦点、分析路径(事实/法律/学理)、核心结论与实践启示;
- 客观书面语, 不出现"本文认为笔者认为"之类第一人称口语句式;
- 只输出摘要正文。"""

def build_keywords_prompt(title: str, abstract: str) -> str:
    return f"""论文题目: 《{title}》
摘要: {abstract}

请提炼论文关键词: 3至5个法学术语, 用全角分号"；"分隔, 按重要性排序。
只输出关键词行本身(不要"关键词:"前缀)。"""

# T2(规范分析型)每章功能指令
CH_GUIDE_T2 = {
    "引言": "三节: 问题的提出(从案例群看共性问题——依次简述每个案例的核心情节并标注来源, 每案一段) / 问题的普遍性分析 / 研究意义与方法。",
    "核心概念与理论基础": "三节: 核心概念界定 / 相关理论基础 / 现行法律规范梳理(法条与司法解释体系化罗列评述)。",
    "司法实践中存在的问题": "归纳二至三个问题, 每问题一节: 表现与特征 / 典型案例印证(引用素材中的具体案件) / 问题根源分析。",
    "域外经验借鉴": "两节: 域外相关制度(可从英美判例法/大陆法系成文法传统中选取与主题相关者概述) / 对我国的启示。本章可精炼, 不宜过长。",
    "完善建议": "三节: 立法层面 / 司法层面 / 配套措施, 对策须与第三章问题一一呼应、有针对性。",
    "结语": "简短收束全文, 不引入新论点, 不分节。",
}

def build_chapter_prompt_t2(title: str, cluster: list, chapter: str, seq: int,
                            word_limit: int, prev_summary: str = "") -> str:
    guide = CH_GUIDE_T2.get(chapter, "按本章在论文中的功能组织论证。")
    blocks = "\n\n".join(build_case_block(c) for c in cluster)
    ctx = f"\n【前文摘要(保持衔接, 勿重复)】\n{prev_summary[:1000]}\n" if prev_summary else ""
    return f"""你是法学本科毕业论文写作者。论文题目: 《{title}》(规范分析型——由案例引出问题)。

本篇论文的案例群素材如下(全部真实, 共{len(cluster)}案):
{blocks}
{ctx}
现在撰写第{seq}章「{chapter}」。本章写作要求:
{guide}
- 小节标题编号规则(严格执行): 二级标题用"{seq}.1 标题文字"、"{seq}.2 标题文字"…独占一行; 如需三级标题用"{seq}.1.1 标题文字"; 禁止使用(一)(二)(三)、一、二、三等中文编号;
- 字数{word_limit}字左右(上限{int(word_limit * LAW_SOFT_MAX_RATIO)}字);
- 法学书面语, 三段论/要件式论证, 禁止口语化;
- 案号/当事人/裁判结果只准引用素材并标注来源;
- 输出纯正文(不要章标题行, 不要markdown符号)。"""

